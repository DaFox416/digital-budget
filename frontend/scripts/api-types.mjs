// Generates src/api/schema.d.ts from the backend's OpenAPI document.
// Usage: npm run api:types (the backend must be running; override the URL with OPENAPI_URL).
// A Node script instead of the CLI so the URL override works the same on Windows and Linux.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const url = process.env.OPENAPI_URL ?? 'http://localhost:8000/openapi.json'
const output = new URL('../src/api/schema.d.ts', import.meta.url)

const ast = await openapiTS(new URL(url))
const header = `// Generated by \`npm run api:types\` from ${url}. Don't edit by hand.\n\n`
await writeFile(output, header + astToString(ast))
console.log(`API types written to src/api/schema.d.ts from ${url}`)
